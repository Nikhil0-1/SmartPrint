  DEVICE_ACCEPTED: ['ACKNOWLEDGED', 'DOWNLOADING', 'PROCESSING', 'FAILED', 'RECOVERY_REQUIRED'],
  ACKNOWLEDGED: ['DOWNLOADING', 'PROCESSING', 'SUBMITTED_TO_CUPS', 'FAILED', 'RECOVERY_REQUIRED'],
